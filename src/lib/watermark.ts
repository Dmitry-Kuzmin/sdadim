/**
 * Водяной знак словаря: доказательство, что копия снята именно с sdadim.eu.
 *
 * После коротких русских слов («в», «на», «не»…) обычный пробел меняется на неразрывный — так делает
 * любая типографика, читателю и поиску не видно. Но меняется не каждый, а по шаблону из хэша
 * (id слова, поле, номер места): у каждого перевода свой рисунок пробелов. Скрапер копирует HTML
 * или JSON вместе с ними — `npm run words:watermark -- <адрес или файл>` находит наш рисунок на чужом сайте.
 * Это улика для жалобы хостингу и Google (DMCA), а не замок: нормализацию пробелов знак не переживает.
 *
 * Менять SALT или правило нельзя: старые копии перестанут опознаваться.
 */
const SALT = "sdadim.eu/wm1";
const NBSP = " ";
/** Короткие слова, после которых неразрывный пробел типографически уместен. */
const SHORT = /(^|[\s(«"])([вкосуиаВКОСУИА]|на|по|за|из|от|до|не|но|ни|же|об|во|со|ко|то|На|По|За|Из|От|До|Не|Но|Во|Со|Об)( )/g;

/** FNV-1a: детерминированный бит места. */
function bit(s: string) {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 0x01000193);
  return (h >>> 0) % 2 === 1;
}

/** Поставить знак в строку. key — id слова и поле: «arcen/ru». */
export function mark(text: string, key: string): string {
  let n = 0;
  return text.replace(SHORT, (_m, pre: string, w: string) => `${pre}${w}${bit(`${SALT}|${key}|${n++}`) ? NBSP : " "}`);
}

/** Сколько мест под знак в строке: строки без мест или с одним не доказывают ничего. */
export const slots = (text: string) => (text.match(SHORT) ?? []).length;

type Marked = { id: string; ru: string; d?: string; h?: string; ex?: { es: string; ru: string } };

/** Знак во всех русских полях слова. Испанские не трогаем: по ним идут игры с вводом и ссылки в статьях. */
export function markWord<T extends Marked>(w: T): T {
  return {
    ...w,
    ru: mark(w.ru, `${w.id}/ru`),
    ...(w.d && { d: mark(w.d, `${w.id}/d`) }),
    ...(w.h && { h: mark(w.h, `${w.id}/h`) }),
    ...(w.ex && { ex: { ...w.ex, ru: mark(w.ex.ru, `${w.id}/ex`) } }),
  };
}
